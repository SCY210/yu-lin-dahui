// Generates lib/username-hanzi-data.ts, the character table that makes simplified and traditional forms of a login
// name the same account (docs/ACCOUNT_LOGIN.md). Source: the OpenCC dictionaries (Apache-2.0,
// vendor/opencc-1.4.2.LICENSE.txt), used only at generation time, never as a runtime dependency.
//
// Usage: node scripts/generate-username-hanzi.mjs <path to OpenCC data/dictionary>
// e.g. after `npm pack opencc@1.4.2` and extracting it: node scripts/generate-username-hanzi.mjs package/data/dictionary
import {readFileSync,writeFileSync} from 'node:fs';
import {join} from 'node:path';

const dir=process.argv[2];
if(!dir){console.error('Usage: node scripts/generate-username-hanzi.mjs <OpenCC data/dictionary directory>');process.exit(1)}
const single=value=>Array.from(value).length===1;
function read(name){
 const rows=[];
 for(const line of readFileSync(join(dir,name),'utf8').split('\n')){
  if(!line||line.startsWith('#'))continue;
  const [key,values]=line.split('\t');if(!values)continue;
  rows.push([key,values.trim().split(/\s+/)]);
 }
 return rows;
}
// Regional variant forms (台灣、香港) back to the standard traditional form: "裡" and "裏" are both "裏".
const standard=new Map();
for(const file of ['TWVariants.txt','HKVariants.txt'])for(const [std,variants] of read(file)){
 if(!single(std))continue;
 for(const v of variants)if(single(v)&&v!==std&&!standard.has(v))standard.set(v,std);
}
// Traditional to simplified, the first (most common) choice for each character.
const simplified=new Map();
for(const [trad,simps] of read('TSCharacters.txt'))if(single(trad)&&single(simps[0])&&simps[0]!==trad)simplified.set(trad,simps[0]);
const step=c=>{const s=standard.get(c)??c;return simplified.get(s)??s};
// Follow each character to a form that no longer changes, so converting twice gives the same name.
const canonical=c=>{let x=c;for(let i=0;i<8;i++){const next=step(x);if(next===x)return x;x=next}throw new Error('No fixed point for '+c)};
const pairs=[...new Set([...standard.keys(),...simplified.keys()])].map(c=>[c,canonical(c)]).filter(([c,s])=>c!==s).sort(([a],[b])=>a.codePointAt(0)-b.codePointAt(0));
for(const [,s] of pairs)if(canonical(s)!==s)throw new Error('Not idempotent: '+s);
const body=pairs.map(([c,s])=>c+s).join('');
writeFileSync('lib/username-hanzi-data.ts',`// Generated by scripts/generate-username-hanzi.mjs from the OpenCC dictionaries (Apache-2.0,
// vendor/opencc-1.4.2.LICENSE.txt): TSCharacters, TWVariants and HKVariants. Do not edit by hand.
// Each pair is a traditional or regional character followed by its simplified form; ${pairs.length} pairs.
export const hanziPairs=${JSON.stringify(body)};
`);
console.log('pairs',pairs.length,'chars',Array.from(body).length);
